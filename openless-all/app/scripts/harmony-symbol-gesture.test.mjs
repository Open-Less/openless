import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';

const source = readFileSync(new URL('../harmony/entry/src/main/ets/inputmethod/SymbolGesture.ets', import.meta.url), 'utf8');
const exports = {};
vm.runInNewContext(ts.transpileModule(source, {
  compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS },
}).outputText, { exports });
const { SymbolGesture, letterSymbol, digitSymbol } = exports;
const gesture = new SymbolGesture();
const field = 'editor1:zh:standard';
gesture.begin('a', field);
assert.equal(gesture.tap('a', field), true);
assert.equal(gesture.tap('a', field), false, 'native click and tap callbacks must not double-insert');
gesture.begin('a', field);
gesture.arm('a', '~', field, 'hold');
assert.equal(gesture.finish('a', field, 'hold'), '~');
assert.equal(gesture.finish('a', field, 'hold'), '', 'release must commit at most once');
assert.equal(gesture.tap('a', field), false, 'a completed long press must not emit its letter');
gesture.begin('a', field);
gesture.arm('a', '~', field, 'swipe');
assert.equal(gesture.cancel('a', 'hold'), false, 'losing long-press recognizer must not cancel the winning swipe');
assert.equal(gesture.move('a', 2, -20, 13), true);
assert.equal(gesture.finish('a', field, 'swipe'), '~');
gesture.begin('a', field);
gesture.arm('a', '~', field, 'swipe');
assert.equal(gesture.move('a', 40, -20, 13), false, 'horizontal drift must not insert a symbol');
assert.equal(gesture.finish('a', field, 'swipe'), '');
gesture.begin('a', field);
gesture.arm('a', '~', field, 'swipe');
assert.equal(gesture.move('a', 0, -18, 25), false, 'a small movement must not arm the default swipe');
assert.equal(gesture.move('a', 18, -28, 25), false, 'diagonal movement must not arm the swipe');
assert.equal(gesture.move('a', 5, -28, 25), true);
assert.equal(gesture.finish('a', field, 'swipe'), '~');
gesture.begin('a', field);
gesture.arm('a', '~', field, 'swipe');
gesture.move('a', 0, -25, 13);
assert.equal(gesture.move('a', 0, -3, 13), false, 'moving back cancels an armed swipe');
assert.equal(gesture.finish('a', field, 'swipe'), '');
gesture.begin('a', field);
gesture.arm('a', '~', field, 'hold');
assert.equal(gesture.finish('a', 'editor2:zh:standard', 'hold'), '', 'held keys cannot cross editors');
gesture.begin('a', field);
gesture.arm('a', '~', field, 'hold');
assert.equal(gesture.finish('a', 'editor1:en:standard', 'hold'), '', 'held keys cannot cross languages');
gesture.begin('a', field);
gesture.arm('a', '~', field, 'hold');
gesture.cancel('a');
assert.equal(gesture.finish('a', field, 'hold'), '');
assert.equal(gesture.tap('a', field), false);
gesture.begin('a', field);
assert.equal(gesture.tap('a', field), true, 'the next physical press is independent');
gesture.begin('left', field); gesture.begin('right', field);
gesture.arm('left', '，', field, 'hold'); gesture.arm('right', '。', field, 'hold');
assert.equal(gesture.finish('left', field, 'hold'), '，');
assert.equal(gesture.finish('right', field, 'hold'), '。');
assert.equal(letterSymbol(1, 4, true, true), '%');
assert.equal(letterSymbol(1, 5, true, true), '%', 'duplicated split G has the same symbol');
assert.equal(letterSymbol(2, 3, true, true), '！');
assert.equal(letterSymbol(2, 4, true, true), '！', 'duplicated split V has the same symbol');
assert.equal(letterSymbol(2, 0, false, false), ',');
assert.equal(letterSymbol(2, 0, false, true), '，');
assert.equal(digitSymbol('6', true), '……', 'multi-character punctuation must not be truncated');
assert.equal(digitSymbol('6', false), '^');
console.log('Harmony symbol gestures: one-shot release, arbitration, cancellation, editor/language changes and split mapping passed');
