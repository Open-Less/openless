#!/usr/bin/env python3
"""Build bounded, offline keyboard dictionaries from immutable upstream sources."""
import collections
import hashlib
import json
import re
import shutil
import sqlite3
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ICE = "da1fbe602e38f26db846fa10120ee64c2b0324c0"
SYM = "c239062ae02961df18ab7da1671d01b4388204e0"
SOURCES = {
    "8105.dict.yaml": (
        f"https://raw.githubusercontent.com/iDvel/rime-ice/{ICE}/cn_dicts/8105.dict.yaml",
        "1f9a42b91dea6982baee2551981780271aeffd78876662b9c9f324e56b37b120"),
    "base.dict.yaml": (
        f"https://raw.githubusercontent.com/iDvel/rime-ice/{ICE}/cn_dicts/base.dict.yaml",
        "0418d5103d8e40c8fff4b686a873ad03e9836cd0419ecae0b7e1e2526312dba0"),
    "rime-ice-LICENSE.txt": (
        f"https://raw.githubusercontent.com/iDvel/rime-ice/{ICE}/LICENSE",
        "3972dc9744f6499f0f9b2dbf76696f2ae7ad8af9b23dde66d6af86c9dfb36986"),
    "frequency_dictionary_en_82_765.txt": (
        f"https://raw.githubusercontent.com/wolfgarbe/SymSpell/{SYM}/SymSpell/frequency_dictionary_en_82_765.txt",
        "c604e1121e398ae7c7fbf777f11e0a0f2fa66eda932cb9fba1321466cf3acd7b"),
    "frequency_bigramdictionary_en_243_342.txt": (
        f"https://raw.githubusercontent.com/wolfgarbe/SymSpell/{SYM}/SymSpell/frequency_bigramdictionary_en_243_342.txt",
        "fd892a160184101dd7ae807ac5a302d01fcea1c47304181a8ed7ed9c94545bcd"),
    "SymSpell-LICENSE.txt": (
        f"https://raw.githubusercontent.com/wolfgarbe/SymSpell/{SYM}/LICENSE",
        "858e5c7e7a38824f33cf466719509884f2ee5e35992dbfce377fec0656545814"),
}


def source(name):
    path = ROOT / ".vendor/prediction-sources" / name
    url, digest = SOURCES[name]
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists():
        data = urllib.request.urlopen(url, timeout=90).read()
        if hashlib.sha256(data).hexdigest() != digest:
            raise RuntimeError(f"Unexpected upstream digest: {name}")
        path.write_bytes(data)
    if hashlib.sha256(path.read_bytes()).hexdigest() != digest:
        raise RuntimeError(f"Cached source digest mismatch: {name}")
    return path


def rime_rows(name):
    for line in source(name).read_text().splitlines():
        if line.startswith("#") or "\t" not in line:
            continue
        fields = line.split("\t")
        if len(fields) >= 3 and re.fullmatch(r"[a-z ]+", fields[1]):
            yield fields[0], fields[1], int(float(fields[2]))


def main():
    for name in SOURCES:
        source(name)
    output = ROOT / "Resources/Prediction"
    output.mkdir(parents=True, exist_ok=True)
    # Retain the complete common-character table plus 200k frequency-ranked
    # words. No alphabetic truncation and no hand-picked suggestion lists.
    characters = list(rime_rows("8105.dict.yaml"))
    words = sorted(
        (row for row in rime_rows("base.dict.yaml") if 2 <= len(row[0]) <= 12),
        key=lambda row: (-row[2], row[0], row[1]))[:200_000]
    entries = sorted(set(characters + words), key=lambda row: (row[1], -row[2], row[0]))
    dictionary = ROOT / "Resources/Rime/pinyin_simp.dict.yaml"
    dictionary.write_text(
        "# Generated by scripts/build-predictions.py; do not edit.\n"
        f"# rime-ice {ICE}; GPL-3.0-only. See Resources/Licenses.\n"
        "---\nname: pinyin_simp\nversion: '2026.10.20-ice-mobile-1'\n"
        "sort: by_weight\n...\n"
        + "".join(f"{word}\t{code}\t{frequency}\n" for word, code, frequency in entries))

    database = output / "lexicon.sqlite3"
    temporary = output / "lexicon.building.sqlite3"
    temporary.unlink(missing_ok=True)
    connection = sqlite3.connect(temporary)
    connection.executescript("""
        PRAGMA journal_mode=OFF;
        PRAGMA synchronous=OFF;
        CREATE TABLE english(word TEXT PRIMARY KEY, frequency INTEGER NOT NULL) WITHOUT ROWID;
        CREATE TABLE bigram(context TEXT, word TEXT, frequency INTEGER NOT NULL,
                            PRIMARY KEY(context, word)) WITHOUT ROWID;
        CREATE TABLE chinese(context TEXT, word TEXT, frequency INTEGER NOT NULL,
                             PRIMARY KEY(context, word)) WITHOUT ROWID;
    """)
    english = []
    for line in source("frequency_dictionary_en_82_765.txt").read_text().splitlines():
        word, frequency = line.rsplit(" ", 1)
        if re.fullmatch(r"[a-z]+(?:'[a-z]+)?", word) and len(word) <= 32:
            english.append((word, int(frequency)))
    connection.executemany("INSERT INTO english VALUES (?,?)", english)
    bigrams = collections.defaultdict(list)
    for line in source("frequency_bigramdictionary_en_243_342.txt").read_text().splitlines():
        before, word, frequency = line.split()
        if re.fullmatch(r"[a-z]+(?:'[a-z]+)?", before) and re.fullmatch(r"[a-z]+(?:'[a-z]+)?", word):
            bigrams[before].append((word, int(frequency)))
    # Top 32 per context is enough for an 8-item bar while retaining prefix
    # matching variety. Bounds file size and avoids loading a model into RAM.
    bigram_rows = [(before, word, frequency) for before, rows in sorted(bigrams.items())
                   for word, frequency in sorted(rows, key=lambda row: (-row[1], row[0]))[:32]]
    connection.executemany("INSERT INTO bigram VALUES (?,?,?)", bigram_rows)
    continuations = collections.defaultdict(dict)
    for phrase, _, frequency in words:
        if not all("\u3400" <= char <= "\u9fff" for char in phrase):
            continue
        for length in range(1, min(4, len(phrase) - 1) + 1):
            before, suffix = phrase[:length], phrase[length:]
            if len(suffix) <= 6:
                continuations[before][suffix] = max(frequency, continuations[before].get(suffix, 0))
    chinese_rows = [(before, word, frequency) for before, rows in sorted(continuations.items())
                    for word, frequency in sorted(rows.items(), key=lambda row: (-row[1], row[0]))[:8]]
    connection.executemany("INSERT INTO chinese VALUES (?,?,?)", chinese_rows)
    connection.executescript("""
        CREATE INDEX english_frequency ON english(frequency DESC);
        CREATE INDEX bigram_frequency ON bigram(context, frequency DESC);
        CREATE INDEX chinese_frequency ON chinese(context, frequency DESC);
        PRAGMA user_version=1;
        VACUUM;
    """)
    connection.commit()
    connection.close()
    temporary.replace(database)
    license_directory = ROOT / "Resources/Licenses"
    for name in ["rime-ice-LICENSE.txt", "SymSpell-LICENSE.txt"]:
        shutil.copyfile(source(name), license_directory / name)
    manifest = {
        "format": 1, "rime_ice_commit": ICE, "symspell_commit": SYM,
        "rime_entries": len(entries), "english_words": len(english),
        "english_bigrams": len(bigram_rows), "chinese_continuations": len(chinese_rows),
        "database_bytes": database.stat().st_size,
        "database_sha256": hashlib.sha256(database.read_bytes()).hexdigest(),
        "sources": {name: {"url": url, "sha256": digest} for name, (url, digest) in SOURCES.items()},
    }
    (output / "manifest.json").write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n")
    print(json.dumps({key: value for key, value in manifest.items() if key != "sources"}, indent=2))


if __name__ == "__main__":
    main()
